"""Draws every example job. Regenerate the gallery with:

PYTHONPATH=examples uv run python -m flows.draw > examples/flows/GRAPHS.md
"""

from __future__ import annotations

from .jobs import ALL, LOSS_RUNS


def render() -> str:
    parts = ["# Example jobs, drawn", "", "Generated by `flows.draw` from the definitions in `jobs.py`.", ""]
    for job in ALL:
        parts += [f"## {job.name}", "", "```mermaid", job.graph().to_mermaid(), "```", ""]
    parts += [
        "## loss_runs, with a run parked at wait_reply_window",
        "",
        "```mermaid",
        LOSS_RUNS.graph().to_mermaid(current="wait_reply_window"),
        "```",
        "",
    ]
    return "\n".join(parts)


if __name__ == "__main__":
    print(render(), end="")
